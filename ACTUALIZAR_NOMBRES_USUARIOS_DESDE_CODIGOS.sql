-- Detiene la ejecucion si el catalogo contiene mas de una persona para la
-- misma combinacion empresa + codigo.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM tmp_nombres_usuarios
    GROUP BY UPPER(BTRIM(empresa)), UPPER(BTRIM(codigo))
    HAVING COUNT(*) > 1
  ) THEN
    RAISE EXCEPTION 'El catalogo contiene codigos duplicados para una empresa';
  END IF;

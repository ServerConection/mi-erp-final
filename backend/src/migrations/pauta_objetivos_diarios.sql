CREATE TABLE IF NOT EXISTS public.pauta_objetivos_diarios (
    id               SERIAL PRIMARY KEY,
    empresa          TEXT           NOT NULL,
    campana          TEXT           NOT NULL,
    fecha            DATE           NOT NULL,
    inversion        NUMERIC(12,2)  NOT NULL DEFAULT 0,
    cpl              NUMERIC(10,4)  NOT NULL DEFAULT 0,
    leads            NUMERIC(12,2)  NOT NULL DEFAULT 0,
    atc              NUMERIC(12,2)  NOT NULL DEFAULT 0,
    fuera_cobertura  NUMERIC(12,2)  NOT NULL DEFAULT 0,
    inegociables     NUMERIC(12,2)  NOT NULL DEFAULT 0,
    gestionables     NUMERIC(12,2)  NOT NULL DEFAULT 0,
    efectividad      NUMERIC(12,2)  NOT NULL DEFAULT 0,
    activo           BOOLEAN        NOT NULL DEFAULT TRUE,
    creado_en        TIMESTAMP      NOT NULL DEFAULT NOW(),
    actualizado_en   TIMESTAMP      NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_pauta_obj_emp_camp_fecha UNIQUE (empresa, campana, fecha)
);

CREATE INDEX IF NOT EXISTS idx_pauta_obj_empresa_fecha
    ON public.pauta_objetivos_diarios (empresa, fecha)
    WHERE activo;

COMMENT ON TABLE public.pauta_objetivos_diarios IS
    'Objetivos diarios de pauta por campana. Alimenta las metas del modulo Indicadores.';

-- Trigger de actualizado_en (mismo patron que public.asesores_metas)
CREATE OR REPLACE FUNCTION public.fn_pauta_obj_set_actualizado_en()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.actualizado_en = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_pauta_obj_actualizado_en ON public.pauta_objetivos_diarios;
CREATE TRIGGER trg_pauta_obj_actualizado_en
    BEFORE UPDATE ON public.pauta_objetivos_diarios
    FOR EACH ROW EXECUTE FUNCTION public.fn_pauta_obj_set_actualizado_en();


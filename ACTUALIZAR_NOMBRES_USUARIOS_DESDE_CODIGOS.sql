    SELECT 1
    FROM public.usuarios u
    JOIN tmp_nombres_usuarios t
      ON UPPER(BTRIM(u.empresa)) = UPPER(BTRIM(t.empresa))
     AND UPPER(BTRIM(u.codigo_vendedor)) = UPPER(BTRIM(t.codigo))
    GROUP BY UPPER(BTRIM(u.empresa)), UPPER(BTRIM(u.codigo_vendedor))
    HAVING COUNT(*) > 1
  ) THEN
    RAISE EXCEPTION 'usuarios contiene codigos duplicados para una empresa';
  END IF;
END
$$;

-- Respaldo permanente de las filas que realmente cambiaran.
CREATE TABLE IF NOT EXISTS public.usuarios_nombres_respaldo (
  respaldo_id     bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  lote            bigint NOT NULL,
  respaldado_en   timestamptz NOT NULL DEFAULT clock_timestamp(),
  usuario_id      bigint NOT NULL,
  empresa         text,
  codigo_vendedor text,
  nombres         text,
  apellidos       text
);

CREATE TEMP TABLE tmp_lote (lote bigint NOT NULL) ON COMMIT DROP;
INSERT INTO tmp_lote VALUES (txid_current());

INSERT INTO public.usuarios_nombres_respaldo
  (lote, usuario_id, empresa, codigo_vendedor, nombres, apellidos)
SELECT l.lote, u.id, u.empresa, u.codigo_vendedor, u.nombres, u.apellidos
FROM public.usuarios u
JOIN tmp_nombres_usuarios t
  ON UPPER(BTRIM(u.empresa)) = UPPER(BTRIM(t.empresa))
 AND UPPER(BTRIM(u.codigo_vendedor)) = UPPER(BTRIM(t.codigo))
CROSS JOIN tmp_lote l
WHERE BTRIM(COALESCE(u.nombres, '')) IS DISTINCT FROM BTRIM(t.nombres)
   OR BTRIM(COALESCE(u.apellidos, '')) IS DISTINCT FROM BTRIM(t.apellidos);

-- Actualiza unicamente nombres y apellidos; conserva login, contrasena,
-- perfil, estado, codigo y el resto de los datos del usuario.
UPDATE public.usuarios u
SET nombres = t.nombres,
    apellidos = t.apellidos
FROM tmp_nombres_usuarios t
WHERE UPPER(BTRIM(u.empresa)) = UPPER(BTRIM(t.empresa))
  AND UPPER(BTRIM(u.codigo_vendedor)) = UPPER(BTRIM(t.codigo))
  AND (
    BTRIM(COALESCE(u.nombres, '')) IS DISTINCT FROM BTRIM(t.nombres)
    OR BTRIM(COALESCE(u.apellidos, '')) IS DISTINCT FROM BTRIM(t.apellidos)
  );

-- Resultado del lote: revise estos datos despues de ejecutar.
SELECT l.lote,
       COUNT(*) AS usuarios_actualizados
FROM public.usuarios_nombres_respaldo r
CROSS JOIN tmp_lote l
WHERE r.lote = l.lote
GROUP BY l.lote;

-- Registros del Excel que no encontraron usuario por empresa + codigo.
SELECT t.empresa, t.codigo, t.nombres, t.apellidos, t.estado
FROM tmp_nombres_usuarios t
LEFT JOIN public.usuarios u
  ON UPPER(BTRIM(u.empresa)) = UPPER(BTRIM(t.empresa))
 AND UPPER(BTRIM(u.codigo_vendedor)) = UPPER(BTRIM(t.codigo))
WHERE u.id IS NULL
ORDER BY t.empresa, t.codigo;

